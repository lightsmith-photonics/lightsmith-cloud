"""Result storage: S3-compatible object storage, or a local directory.

Keys are generated by the server from job ids (``<job_id>.json.gz``) and
checked against a strict pattern, so no client input ever becomes a path.
"""

from __future__ import annotations

import gzip
import re
from pathlib import Path
from typing import Protocol

from .config import Settings

KEY_RE = re.compile(r"^[0-9a-f]{32}\.json\.gz$")


def result_key(job_id: str) -> str:
    key = f"{job_id}.json.gz"
    if not KEY_RE.match(key):
        raise ValueError(f"invalid result key {key!r}")
    return key


def _check(key: str) -> str:
    if not KEY_RE.match(key):
        raise ValueError(f"invalid result key {key!r}")
    return key


class ResultStore(Protocol):
    def put(self, key: str, data: bytes) -> int: ...  # stores gzip(data); returns the uncompressed size
    def get(self, key: str) -> bytes: ...  # uncompressed bytes
    def delete(self, key: str) -> None: ...


class LocalStore:
    def __init__(self, root: Path):
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        p = (self.root / _check(key)).resolve()
        if p.parent != self.root:
            raise ValueError("result key escapes the store")
        return p

    def put(self, key: str, data: bytes) -> int:
        p = self._path(key)
        tmp = p.with_suffix(".tmp")
        tmp.write_bytes(gzip.compress(data, compresslevel=5))
        tmp.replace(p)
        return len(data)

    def get(self, key: str) -> bytes:
        return gzip.decompress(self._path(key).read_bytes())

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Store:
    """Any S3-compatible service (AWS S3, Cloudflare R2, Backblaze B2, SeaweedFS, ...)."""

    def __init__(self, bucket: str, *, prefix: str = "results/", endpoint_url: str | None = None,
                 region: str | None = None, client=None, create_bucket: bool = False):
        if client is None:
            import boto3

            client = boto3.client("s3", endpoint_url=endpoint_url, region_name=region)
        self.client, self.bucket, self.prefix = client, bucket, prefix
        if create_bucket:  # dev stacks (e.g. SeaweedFS in compose) start without the bucket
            try:
                client.head_bucket(Bucket=bucket)
            except Exception:
                client.create_bucket(Bucket=bucket)

    def put(self, key: str, data: bytes) -> int:
        self.client.put_object(Bucket=self.bucket, Key=self.prefix + _check(key), Body=gzip.compress(data, 5),
                               ContentType="application/json", ContentEncoding="gzip")
        return len(data)

    def get(self, key: str) -> bytes:
        obj = self.client.get_object(Bucket=self.bucket, Key=self.prefix + _check(key))
        return gzip.decompress(obj["Body"].read())

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self.prefix + _check(key))


def make_store(settings: Settings) -> ResultStore:
    if settings.s3_bucket:
        return S3Store(settings.s3_bucket, prefix=settings.s3_prefix, endpoint_url=settings.s3_endpoint_url,
                       region=settings.s3_region, create_bucket=settings.s3_create_bucket)
    return LocalStore(settings.results_dir)
